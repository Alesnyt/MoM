def snapshot() -> dict:
    saved = store.get_llm_settings()
    return {
        "version": saved["version"] if saved else 0,
        "protocol_prompt": saved["protocol_prompt"] if saved else PROTOCOL_PROMPT,
        "name_review_prompt": saved["name_review_prompt"] if saved else NAME_REVIEW_PROMPT,
        "name_review_enabled": saved["name_review_enabled"] if saved else True,
    }


def settings_view() -> dict:
    return {**snapshot(), "defaults": {
        "protocol_prompt": PROTOCOL_PROMPT,
        "name_review_prompt": NAME_REVIEW_PROMPT,
    }}
